#!/usr/bin/env python3
"""Builds data/modelnames.{lcs,vcs}.txt from the community name dumps.

The hash -> name tables are the ones shipped with guard3's g3DTZ (MIT), which in
turn were brute forced by the modding community. This script only converts the C++
`.inc` initialiser lists into a plain text table the kit can read at runtime:

    data/modelnames.lcs.txt   "971e421c player"  (one per line)

Nothing is copied from the game itself; no binary data is involved.

Usage:
    python tools/build_modelnames.py --g3dtz refs/g3DTZ --out data
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ENTRY = re.compile(r"\{\s*(0x[0-9a-fA-F]{1,8})\s*,\s*\"([^\"]*)\"\s*\}")


def convert(source: Path) -> list[tuple[int, str]]:
    pairs: list[tuple[int, str]] = []
    if not source.is_file():
        return pairs
    text = source.read_text(encoding="utf-8", errors="replace")
    for match in ENTRY.finditer(text):
        pairs.append((int(match.group(1), 16), match.group(2)))
    # stable output, duplicates collapsed (later wins, same as a C++ map)
    deduped: dict[int, str] = {}
    for value, name in pairs:
        deduped[value] = name
    return sorted(deduped.items())


def write(out: Path, game: str, pairs: list[tuple[int, str]]) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "; hash -> model name table for GTA " + game.upper(),
        "; generated by tools/build_modelnames.py from the g3DTZ name dumps (MIT)",
        "; format: 8 hex digits, space, name",
        "",
    ]
    lines += ["%08x %s" % (value, name) for value, name in pairs]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s (%d names)" % (out, len(pairs)))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--g3dtz", default="refs/g3DTZ", help="path to the g3DTZ checkout")
    parser.add_argument("--out", default="data", help="output folder")
    args = parser.parse_args()

    root = Path(args.g3dtz) / "source" / "names"
    out = Path(args.out)

    lcs = convert(root / "lcsnames.inc")
    vcs = convert(root / "vcsnames.inc") + convert(root / "bruteforcedvcsnames.inc")
    vcs_dedup: dict[int, str] = {}
    for value, name in vcs:
        vcs_dedup[value] = name
    vcs_pairs = sorted(vcs_dedup.items())

    if not lcs and not vcs_pairs:
        print("no name tables found under %s" % root)
        return 1

    write(out / "modelnames.lcs.txt", "lcs", lcs)
    write(out / "modelnames.vcs.txt", "vcs", vcs_pairs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())